//! Startup asset verification: the Runtime Image and every file in it must be
//! present and hash-pinned.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use dont_get_rusty::assets::{FETCH_COMMAND, RuntimeImage};
use sha2::{Digest, Sha256};

fn sha256_file(path: &Path) -> String {
    let mut hasher = Sha256::new();
    hasher.update(fs::read(path).unwrap());
    hasher
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// Every file in the image, as an image-relative path.
fn image_files(root: &Path) -> BTreeSet<PathBuf> {
    fn walk(root: &Path, dir: &Path, out: &mut BTreeSet<PathBuf>) {
        for entry in fs::read_dir(dir).unwrap() {
            let entry = entry.unwrap();
            let path = entry.path();
            if entry.file_type().unwrap().is_dir() {
                walk(root, &path, out);
            } else {
                out.insert(path.strip_prefix(root).unwrap().to_path_buf());
            }
        }
    }

    let mut files = BTreeSet::new();
    files.insert(PathBuf::from("python.wasm"));
    walk(root, &root.join("lib/python3.15"), &mut files);
    files
}

/// Writes a `checksums.txt` covering every image file, as the fetch script does.
fn write_checksums(root: &Path) {
    let mut text = String::from("# generated by the test\n");
    for relative in image_files(root) {
        text.push_str(&format!(
            "{}  {}\n",
            sha256_file(&root.join(&relative)),
            relative.display()
        ));
    }
    fs::write(root.join("checksums.txt"), text).unwrap();
}

#[test]
fn missing_runtime_image_names_the_fetch_script() {
    let dir = tempfile::tempdir().unwrap();

    let err = RuntimeImage::locate(dir.path()).unwrap_err();
    let message = err.to_string();

    assert!(message.contains(FETCH_COMMAND), "message: {message}");
}

#[test]
fn missing_checksums_names_the_fetch_script() {
    let dir = tempfile::tempdir().unwrap();
    fs::create_dir_all(dir.path().join("lib/python3.15")).unwrap();
    fs::write(dir.path().join("python.wasm"), b"not the pinned guest").unwrap();

    let err = RuntimeImage::locate(dir.path()).unwrap_err();
    let message = err.to_string();

    assert!(message.contains("checksums.txt"), "message: {message}");
    assert!(message.contains(FETCH_COMMAND), "message: {message}");
}

#[test]
fn mismatched_wasm_hash_names_the_fetch_script() {
    let dir = tempfile::tempdir().unwrap();
    fs::create_dir_all(dir.path().join("lib/python3.15")).unwrap();
    fs::write(dir.path().join("python.wasm"), b"not the pinned guest").unwrap();
    write_checksums(dir.path());

    // The checksums match the file on disk, but `python.wasm` still fails the
    // pin compiled into the binary.
    let err = RuntimeImage::locate(dir.path()).unwrap_err();
    let message = err.to_string();

    assert!(message.contains(FETCH_COMMAND), "message: {message}");
    assert!(
        message.to_lowercase().contains("sha-256") || message.to_lowercase().contains("hash"),
        "message: {message}"
    );
}

#[test]
fn a_tampered_stdlib_file_is_refused_by_name() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    let image = RuntimeImage::discover().expect("run `scripts/fetch-assets.sh` first");
    let python_wasm = image
        .python_wasm()
        .canonicalize()
        .expect("the Runtime Image path should resolve");
    std::os::unix::fs::symlink(python_wasm, root.join("python.wasm")).unwrap();
    fs::create_dir_all(root.join("lib/python3.15")).unwrap();
    fs::write(root.join("lib/python3.15/evil.py"), "original\n").unwrap();
    write_checksums(root);

    fs::write(root.join("lib/python3.15/evil.py"), "tampered\n").unwrap();

    let err = RuntimeImage::locate(root).unwrap_err();
    let message = err.to_string();

    assert!(message.contains("evil.py"), "message: {message}");
    assert!(message.contains(FETCH_COMMAND), "message: {message}");
    assert!(
        message.to_lowercase().contains("sha-256") || message.to_lowercase().contains("corrupt"),
        "message: {message}"
    );
}

#[test]
fn checksums_lists_every_image_file() {
    let image = RuntimeImage::discover().expect("run `scripts/fetch-assets.sh` first");
    let text = fs::read_to_string(image.root().join("checksums.txt")).unwrap();
    let mut listed = BTreeSet::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (_, relative) = line.split_once("  ").expect("`<sha256>  <path>`");
        listed.insert(PathBuf::from(relative));
    }

    assert_eq!(
        listed,
        image_files(image.root()),
        "the fetch script must pin every file in the image"
    );
    assert!(listed.contains(Path::new("python.wasm")));
}

#[test]
fn locate_accepts_the_fetched_runtime_image() {
    let image = RuntimeImage::discover().expect("run `scripts/fetch-assets.sh` first");

    assert!(image.python_wasm().ends_with("python.wasm"));
    assert!(image.root().join("lib/python3.15").is_dir());
}
